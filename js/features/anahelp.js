function _set(el, t, d) {
  if (!el || el.hasAttribute('data-help')) return;
  el.setAttribute('data-help-title', t);
  el.setAttribute('data-help', d);
}

function stamp() {
  const v = $('analysisView');
  if (!v) return;
  v.querySelectorAll('.ana-sec[data-sub]').forEach(s => { const x = SUB[s.dataset.sub]; if (x) _set(s, x[0], x[1]); });
  v.querySelectorAll('section.sb-card, section.an-card').forEach(c => {
    const h = c.querySelector('h2, h3');
    const t = h ? h.textContent.trim() : '';
    if (!t) return;
    const re = CARD_RE.find(([r]) => r.test(t));
    const d = CARD[t] || (re && re[1]);
    if (d) _set(c, t, d);
  });
  BLOCK.forEach(([sel, t, d]) => v.querySelectorAll(sel).forEach(el => _set(el, t, d)));
  v.querySelectorAll('[onclick]').forEach(el => {
    const on = el.getAttribute('onclick') || '';
    const m = BTN.find(([k]) => on.startsWith(k));
    if (m) _set(el, m[1], m[2]);
  });
}

function _init() {
  const v = $('analysisView');
  if (!v) return;
  stamp();
  // 카드가 다시 그려질 때마다 (요소 추가만 지켜봄 → 속성을 붙여도 다시 불리지 않음)
  //   MutationObserver 가 이미 한 번에 모아 부르므로 바로 붙인다 (rAF로 미루면 백그라운드 탭 등에서 프레임이 멈춰 밀린다)
  if (window.MutationObserver) new MutationObserver(stamp).observe(v, { childList: true, subtree: true });
  // 서브탭: 안내 모드에서도 바뀌고(onclick이 먼저) 그 서브탭 설명을 띄움
  const nav = $('anaSubnav');
  if (nav) nav.addEventListener('click', e => {
    if (!document.body.classList.contains('help-mode')) return;
    const b = e.target.closest('.ana-sub');
    const x = b && SUB[b.dataset.sub];
    if (x && window.showHelpModeTooltip) window.showHelpModeTooltip(b.textContent.trim() || x[0], x[1]);
  });
}

if (typeof window !== 'undefined') {
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', () => setTimeout(_init, 0));
  else setTimeout(_init, 0);
}
